def validate_registry() -> list[AgentDefinition]:
    if len(AGENT_DEFINITIONS) != 50:
        raise RuntimeError(f"Sagaidīti 50 aģenti, atrasti {len(AGENT_DEFINITIONS)}")
    ids = [a.id for a in AGENT_DEFINITIONS]
    if len(set(ids)) != 50:
        raise RuntimeError("Aģentu ID nav unikāli")
    numbers = [a.number for a in AGENT_DEFINITIONS]
    if sorted(numbers) != list(range(1, 51)):
        raise RuntimeError("Aģentu numuriem jābūt 1..50")
    return AGENT_DEFINITIONS


def list_agents() -> list[AgentDefinition]:
    return list(validate_registry())


def get_agent(agent_id: str) -> AgentDefinition:
    for agent in AGENT_DEFINITIONS:
        if agent.id == agent_id or agent.id.lower() == agent_id.lower():
            return agent
    raise KeyError(f"Aģents nav atrasts: {agent_id}")


def list_sections() -> dict[str, list[AgentDefinition]]:
    sections: dict[str, list[AgentDefinition]] = {}
    for agent in list_agents():
        sections.setdefault(agent.section, []).append(agent)
    return sections


